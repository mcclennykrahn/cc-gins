"""Simulation: vehicle trajectory, MEMS IMU, GNSS (noise, outages, slow-drift spoofing).

Frames: nav = local ENU, body = FLU (x forward, y left, z up). g = [0, 0, -9.81].
The IMU samples are generated by *inverting* the discrete mechanization used in
`ccgins.filters`, so that error-free IMU data reproduces the truth exactly.
"""
from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from .timing import in_window

from .geometry import euler_to_rot, so3_exp, so3_log

G_NAV = np.array([0.0, 0.0, -9.81])
DEG = np.pi / 180.0


@dataclass
class Truth:
    t: np.ndarray        # (N,)
    R: np.ndarray        # (N,3,3) body->nav
    v: np.ndarray        # (N,3) nav velocity
    p: np.ndarray        # (N,3) nav position
    v_body: np.ndarray   # (N,3) body-frame velocity (FLU)
    gyro: np.ndarray     # (N,3) true angular rate, rad/s
    accel: np.ndarray    # (N,3) true specific force, m/s^2
    dt: float


@dataclass
class ImuSpec:
    """MEMS error model (defaults ~ low-cost industrial MEMS)."""
    gyro_arw: float = 0.3          # deg/sqrt(h)
    accel_vrw: float = 0.1         # m/s/sqrt(h)
    gyro_bias_sigma: float = 30.0  # deg/h, turn-on bias
    accel_bias_sigma: float = 5.0  # mg, turn-on bias
    gyro_bias_rw: float = 3.0      # deg/h/sqrt(h)  (bias random walk)
    accel_bias_rw: float = 0.05    # mg/sqrt(s)
    vib_accel_per_mps: float = 0.02   # m/s^2 per (m/s) of speed (road vibration, white)
    vib_gyro_per_mps: float = 0.002   # deg/s per (m/s) of speed

    def densities(self, vmax: float = 20.0) -> dict:
        """White-noise densities for the filter (incl. vibration at speed vmax, dt-independent)."""
        return dict(
            gyro=self.gyro_arw * DEG / 60.0,
            accel=self.accel_vrw / 60.0,
            gyro_bias_rw=self.gyro_bias_rw * DEG / 3600.0 / 60.0,
            accel_bias_rw=self.accel_bias_rw * 1e-3 * 9.81,
            vib_accel=self.vib_accel_per_mps * vmax,
            vib_gyro=self.vib_gyro_per_mps * DEG * vmax,
        )


@dataclass
class GnssSpec:
    rate_hz: float = 1.0
    sigma_h: float = 1.0
    sigma_v: float = 2.0
    mp_sigma: float = 0.5      # correlated (multipath-like) error, Gauss-Markov
    mp_tau: float = 30.0
    lever_arm: np.ndarray = field(default_factory=lambda: np.array([0.5, 0.0, 1.2]))
    outages: list = field(default_factory=list)          # [(start_s, duration_s), ...]
    spoof_start: float | None = None
    spoof_rate: float = 0.0                              # m/s horizontal drift
    spoof_dir_deg: float = 45.0


@dataclass
class ImuData:
    t: np.ndarray
    gyro: np.ndarray
    accel: np.ndarray
    gyro_bias: np.ndarray
    accel_bias: np.ndarray
    dt: float


@dataclass
class GnssData:
    t: np.ndarray        # epoch times
    idx: np.ndarray      # IMU index of each epoch
    pos: np.ndarray      # (M,3) antenna position measurements
    valid: np.ndarray    # (M,) bool, False during outages
    spoofed: np.ndarray  # (M,) bool
    sigma: np.ndarray    # (3,) nominal sigma
    sigma_ep: np.ndarray | None = None  # (M,3) optional per-epoch reported sigma (real data)


def _smooth(x: np.ndarray, tau_samples: float) -> np.ndarray:
    a = 1.0 / max(tau_samples, 1.0)
    y = np.empty_like(x)
    acc = x[0]
    for i, xi in enumerate(x):
        acc = acc + a * (xi - acc)
        y[i] = acc
    return y


def generate_trajectory(duration: float = 600.0, dt: float = 0.01, seed: int = 0,
                        vmax: float = 20.0, *, earth: dict | None = None) -> Truth:
    """Generate local ENU truth and invert mechanization for the given Earth model."""
    if not np.isfinite([duration, dt, vmax]).all() or duration <= 0 or dt <= 0 or vmax < 0:
        raise ValueError("trajectory requires finite positive duration and dt and nonnegative vmax")
    rng = np.random.default_rng(seed)
    n = int(round(duration / dt)) + 1
    if n < 2:
        raise ValueError("trajectory must span at least one IMU interval")
    t = np.arange(n) * dt

    # speed profile: piecewise targets, rate-limited (|a| <= 2 m/s^2)
    u_target = np.empty(n)
    i = 0
    first = True
    while i < n:
        seg = max(1, int(rng.uniform(15, 50) / dt))
        if first:
            tgt = 0.0
            seg = max(1, int(5 / dt))
            first = False
        elif rng.random() < 0.1:
            tgt = 0.0
        else:
            tgt = rng.uniform(min(4.0, vmax), vmax)
        u_target[i:i + seg] = tgt
        i += seg
    u = np.empty(n)
    cur = 0.0
    for k in range(n):
        dv = np.clip(u_target[k] - cur, -2.0 * dt, 1.5 * dt)
        cur += dv
        u[k] = cur

    # yaw-rate profile: straight segments and turns, lateral-accel limited
    r_target = np.zeros(n)
    i = int(10 / dt)
    while i < n:
        seg = max(1, int(rng.uniform(5, 25) / dt))
        if rng.random() < 0.45:
            r_target[i:i + seg] = rng.uniform(-0.25, 0.25)
        i += seg
    r = _smooth(r_target, 1.0 / dt)
    r = np.where(u > 0.5, r, 0.0)
    r = np.clip(r, -3.5 / np.maximum(u, 1.0), 3.5 / np.maximum(u, 1.0))
    r = _smooth(r, 0.3 / dt)

    yaw0 = rng.uniform(-np.pi, np.pi)
    yaw = yaw0 + np.cumsum(r) * dt
    ph = rng.uniform(0, 2 * np.pi, 2)
    pitch = 0.03 * np.sin(2 * np.pi * t / 140.0 + ph[0]) + 0.01 * np.sin(2 * np.pi * t / 37.0 + ph[1])
    alat = u * r
    roll = -0.01 * alat + 0.003 * np.sin(2 * np.pi * t / 23.0)
    pitch = pitch + 0.004 * _smooth(np.gradient(u, dt), 0.5 / dt)  # squat/dive

    R = np.stack([euler_to_rot(roll[k], pitch[k], yaw[k]) for k in range(n)])

    # body velocity: forward speed, small slip ~ u*r, small vertical
    slip = 0.015 * u * r + 0.01 * _smooth(rng.standard_normal(n), 0.5 / dt) * (u > 0.5)
    w = 0.01 * _smooth(rng.standard_normal(n), 0.3 / dt) * (u > 0.5)
    v_body = np.stack([u, slip, w], axis=1)
    v = np.einsum("nij,nj->ni", R, v_body)

    # positions + IMU by inverting mechanization
    gravity = G_NAV if earth is None else earth["g"]
    earth_rate = None if earth is None else earth["w_ie"]
    if earth_rate is not None:
        earth_increment = so3_exp(earth_rate * dt)
        coriolis = 2.0 * np.cross(earth_rate, v)
    p = np.zeros((n, 3))
    gyro = np.zeros((n, 3))
    accel = np.zeros((n, 3))
    for k in range(n - 1):
        a = (v[k + 1] - v[k]) / dt
        p[k + 1] = p[k] + v[k] * dt + 0.5 * a * dt * dt
        next_attitude = R[k + 1]
        specific_force = a - gravity
        if earth_rate is not None:
            next_attitude = earth_increment @ next_attitude
            specific_force += coriolis[k]
        gyro[k] = so3_log(R[k].T @ next_attitude) / dt
        accel[k] = R[k].T @ specific_force
    gyro[-1] = gyro[-2]
    accel[-1] = accel[-2]
    return Truth(t=t, R=R, v=v, p=p, v_body=v_body, gyro=gyro, accel=accel, dt=dt)


def simulate_imu(truth: Truth, spec: ImuSpec, seed: int = 0, noise: bool = True) -> ImuData:
    rng = np.random.default_rng(seed + 10_000)
    n, dt = len(truth.t), truth.dt
    if not noise:
        z = np.zeros((n, 3))
        return ImuData(truth.t, truth.gyro.copy(), truth.accel.copy(), z, z.copy(), dt)
    d = spec.densities()
    bg0 = rng.standard_normal(3) * spec.gyro_bias_sigma * DEG / 3600.0
    ba0 = rng.standard_normal(3) * spec.accel_bias_sigma * 1e-3 * 9.81
    bg = bg0 + np.cumsum(rng.standard_normal((n, 3)) * d["gyro_bias_rw"] * np.sqrt(dt), axis=0)
    ba = ba0 + np.cumsum(rng.standard_normal((n, 3)) * d["accel_bias_rw"] * np.sqrt(dt), axis=0)
    speed = np.abs(truth.v_body[:, :1])
    ng = rng.standard_normal((n, 3)) * (d["gyro"] / np.sqrt(dt) + spec.vib_gyro_per_mps * DEG * speed)
    na = rng.standard_normal((n, 3)) * (d["accel"] / np.sqrt(dt) + spec.vib_accel_per_mps * speed)
    return ImuData(truth.t, truth.gyro + bg + ng, truth.accel + ba + na, bg, ba, dt)


def simulate_gnss(truth: Truth, spec: GnssSpec, seed: int = 0) -> GnssData:
    if not np.isfinite(spec.rate_hz) or spec.rate_hz <= 0:
        raise ValueError("GNSS rate must be finite and positive")
    if spec.rate_hz > 1.0 / truth.dt:
        raise ValueError("GNSS rate exceeds IMU grid resolution")
    step = int(round(1.0 / (spec.rate_hz * truth.dt)))
    rng = np.random.default_rng(seed + 20_000)
    idx = np.arange(step, len(truth.t), step)
    t = truth.t[idx]
    m = len(idx)
    sig = np.array([spec.sigma_h, spec.sigma_h, spec.sigma_v])
    white = rng.standard_normal((m, 3)) * sig
    # Epochs are rounded to the IMU grid: use elapsed time, not requested rate.
    a = np.exp(-step * truth.dt / spec.mp_tau)
    mp = np.zeros((m, 3))
    for k in range(1, m):
        mp[k] = a * mp[k - 1] + np.sqrt(1 - a * a) * spec.mp_sigma * rng.standard_normal(3)
    ant = truth.p[idx] + np.einsum("nij,j->ni", truth.R[idx], spec.lever_arm)
    pos = ant + white + mp
    valid = np.ones(m, bool)
    for (s, dur) in spec.outages:
        valid &= ~in_window(t, s, s + dur)
    spoofed = np.zeros(m, bool)
    if spec.spoof_start is not None:
        spoofed = t >= spec.spoof_start
        dirv = np.array([np.cos(spec.spoof_dir_deg * DEG), np.sin(spec.spoof_dir_deg * DEG), 0.0])
        off = np.clip(t - spec.spoof_start, 0, None)[:, None] * spec.spoof_rate * dirv
        pos = pos + off
    return GnssData(t=t, idx=idx, pos=pos, valid=valid, spoofed=spoofed, sigma=sig)
